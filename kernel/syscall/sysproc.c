/* ================================================================
 * sys_exit — 终止当前进程
 * ================================================================ */
uint64 sys_exit(void) {
  int n;
  argint(0, &n);
  exit(n);
  return 0;  /* never reached */
}

/* ================================================================
 * sys_fork — 创建子进程
 * ================================================================ */
uint64 sys_fork(void) {
  return fork();
}

/* ================================================================
 * sys_wait — 等待子进程退出
 * ================================================================ */
uint64 sys_wait(void) {
  uint64 p;
  argaddr(0, &p);
  return wait(p);
}

